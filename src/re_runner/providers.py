"""Optional radare2 static provider. Trusted configuration supplies an executable path."""
import os
import shutil
from pathlib import Path

from .errors import InvalidInput
from .execution import run_command
from .safety import Budget, atomic_json, parse_json, redact


def radare2(path: Path, output: Path, budget: Budget) -> dict | None:
    executable = os.environ.get("RE_RUN_R2") or shutil.which("r2")
    if not executable:
        return None
    executable_path = Path(executable)
    if not executable_path.is_file() or executable_path.suffix.lower() in (".bat", ".cmd", ".ps1", ".sh"):
        raise InvalidInput("RE_RUN_R2 must reference the trusted native r2 executable")
    keep = ("PATH", "SYSTEMROOT", "WINDIR", "COMSPEC", "PATHEXT", "TEMP", "TMP", "TMPDIR")
    env = {key: os.environ[key] for key in keep if key in os.environ}
    # R2_ARGS, user startup scripts and external plugins must never alter commands.
    # R2_NOPLUGINS=1 only disables extra plugin dirs; built-in analyzers stay.
    # R2_PLUGINS_ORDER must stay unset: r2 6.2.4-w64 aborts plugin registration
    # whenever that variable is set (any value), which also drops the built-in
    # x86 decoder ("anal.arch: cannot find 'x86'") and yields an empty aflj.
    env["R2_NOPLUGINS"] = "1"
    version = run_command([str(executable_path), "-qv"], output, budget, timeout=5, env=env)
    tool_version = (version.stdout or version.stderr).strip().splitlines()[0] if version.stdout or version.stderr else "unknown"
    records = [{"argv": [str(executable_path), "-qv"], "status": version.status, "exit_code": version.exit_code}]
    atomic_json(output / "radare2-version-run.json", redact({
        "argv": records[0]["argv"], "status": version.status, "exit_code": version.exit_code,
        "stdout": version.stdout, "stderr": version.stderr,
    }))
    if version.status != "succeeded":
        return {"name": "radare2", "version": tool_version, "status": version.status, "error": "Version probe failed", "runs": records}
    arguments = [str(executable_path), "-NN", "-S", "-q", "-e", "scr.color=0", "-e", "scr.interactive=0", "-e", "io.cache=false"]
    # Snapshot filenames are generated by intake; commands contain only fixed text.
    argv = [*arguments, "-c", "aaa;aflj", str(path.absolute())]
    execution = run_command(argv, output, budget, timeout=min(30, budget.limits["tool_timeout_seconds"]), env=env)
    records.append({"argv": argv, "status": execution.status, "exit_code": execution.exit_code, "timed_out": execution.timed_out})
    atomic_json(output / "radare2-functions-run.json", redact({"argv": argv, "version": tool_version, "status": execution.status, "exit_code": execution.exit_code, "stdout": execution.stdout, "stderr": execution.stderr}))
    if execution.status != "succeeded":
        return {"name": "radare2", "version": tool_version, "status": execution.status, "runs": records, "error": "Static function analysis failed or exceeded budget"}
    try:
        functions = parse_json(execution.stdout)
    except InvalidInput:
        return {"name": "radare2", "version": tool_version, "status": "failed", "runs": records, "error": "Invalid function-list JSON"}
    if not isinstance(functions, list) or not all(isinstance(item, dict) for item in functions):
        return {"name": "radare2", "version": tool_version, "status": "failed", "runs": records, "error": "Provider function result violates contract"}
    if not functions:
        return {
            "name": "radare2", "version": tool_version, "status": "degraded",
            "functions": [], "selected_disassembly": None, "runs": records,
            "error": "No functions recovered; exit code zero does not establish function-analysis coverage",
            "diagnostic": execution.stderr[:2000],
        }
    # r2 6.2.4 aflj names the address field "addr"; older builds used "offset".
    def _address(item: dict) -> int | None:
        value = item.get("addr", item.get("offset"))
        return value if isinstance(value, int) and 0 <= value < 2**64 else None

    function_records = [{key: item.get(key) for key in ("addr", "offset", "name", "size", "nbbs", "nargs", "nlocals", "callrefs", "codexrefs")} for item in functions[:2000]]
    selected = next((address for address in (_address(item) for item in functions) if address is not None), None)
    disassembly = None
    if selected:
        command = "pdj 48 @ " + str(selected)
        argv = [*arguments, "-c", command, str(path.absolute())]
        execution = run_command(argv, output, budget, timeout=10, env=env)
        records.append({"argv": argv, "status": execution.status, "exit_code": execution.exit_code, "timed_out": execution.timed_out})
        atomic_json(output / "radare2-disassembly-run.json", redact({"argv": argv, "version": tool_version, "status": execution.status, "exit_code": execution.exit_code, "stdout": execution.stdout, "stderr": execution.stderr}))
        if execution.status == "succeeded":
            try:
                values = parse_json(execution.stdout)
                if isinstance(values, list):
                    disassembly = [{key: item.get(key) for key in ("addr", "offset", "bytes", "opcode", "type", "jump", "fail")} for item in values[:48] if isinstance(item, dict)]
            except InvalidInput:
                pass
    complete = bool(disassembly)
    return {
        "name": "radare2", "version": tool_version,
        "status": "succeeded" if complete else "degraded",
        "functions": function_records, "selected_disassembly": disassembly, "runs": records,
        "error": None if complete else "Function inventory exists but selected disassembly is missing or invalid",
        "mode": "static, read-only, startup/scripts/plugins disabled",
    }

